"""Decide whether a failed CI job is inside the study's scope.

The evaluation plan scopes the study to build, test, dependency, configuration
and environment failures, and excludes lint-only, documentation-only and
administrative failures because the taxonomy and the prototype do not claim to
diagnose them.

Two places need that decision and they must agree: triage, which drops
out-of-scope cases from the cohort, and the repository assessment, which reports
what a repository's history can contribute. The rule therefore lives here and is
imported by both.

Classification uses the failing job's name and the name of the step that failed.
The GitHub runs API does not expose the underlying shell command, so these names
are a proxy; every tool that uses this prints its classifications so they can be
spot-checked against the real jobs.
"""

from __future__ import annotations

from typing import Tuple

# Dependency bots and scheduled scanners produce short, near-identical failures
# that are automation rather than CI faults. The rule lives here, beside the
# other scope rules, so collection, triage and the repository assessment all
# apply it -- it previously sat in the scouting tool, and 35 bot runs reached an
# eligible cohort because collection could not see it.
BOT_MARKERS: Tuple[str, ...] = (
    "dependabot",
    "renovate",
    " - update #",
    "scorecard",
    "codeql",
    "pre-commit.ci",
    "dependency submission",
    "dependency-submission",
    "code scanning",
)

BOT_ACTORS: Tuple[str, ...] = ("dependabot", "renovate", "github-actions")


def is_bot_run(run: dict) -> bool:
    """True when a workflow run was generated by automation, not a human change."""
    name = (run.get("name") or run.get("workflow_name") or "").lower()
    actor = run.get("triggering_actor") or {}
    login = (actor.get("login") if isinstance(actor, dict) else "") or ""
    job = (run.get("failing_job") or "").lower()
    if any(marker in name for marker in BOT_MARKERS):
        return True
    if any(marker in job for marker in BOT_MARKERS):
        return True
    return any(marker in login.lower() for marker in BOT_ACTORS)


IN_SCOPE = "build_test"
UNKNOWN = "unclassified"

# Excluded buckets are tested first and in this order, because a job named
# "Build docs" is documentation work rather than a build, and "build" would
# otherwise match it.
EXCLUDED_PATTERNS: Tuple[Tuple[str, Tuple[str, ...]], ...] = (
    ("docs", ("doc", "javadoc", "sphinx", "mkdocs", "readme", "changelog")),
    (
        "lint_format",
        (
            "lint",
            "flake8",
            "eslint",
            "prettier",
            "format",
            "style",
            "checkstyle",
            "ruff",
            "black",
            "isort",
            "spotless",
            "clippy",
        ),
    ),
    ("spell", ("spell", "codespell", "typo")),
    (
        "admin_other",
        (
            "commit message",
            "commit prefix",
            "conventional commit",
            "pr title",
            "label",
            "stale",
            "triage",
            "codeql",
            "scorecard",
            "license",
            "contributor",
            "welcome",
            "greet",
            "codeowners",
            "assign",
        ),
    ),
)

IN_SCOPE_PATTERNS: Tuple[str, ...] = (
    "build",
    "compile",
    "assemble",
    "package",
    "gradle",
    "maven",
    "mvn",
    "make",
    "test",
    "pytest",
    "junit",
    "jest",
    "spec",
    "unittest",
    "integration",
    "e2e",
    "install",
    "dependenc",
    "resolve",
    "npm ci",
    "pip install",
    "bundle",
    "setup",
    "environment",
    "docker",
    "container",
    "provision",
    "sanity",
    "check",
)

# Buckets other than IN_SCOPE and UNKNOWN are excluded from the cohort.
EXCLUDED_BUCKETS = tuple(name for name, _ in EXCLUDED_PATTERNS)


def classify_job(job_name: str, step_name: str) -> str:
    """Bucket a failed job from its name and the name of the step that failed."""
    text = f"{job_name or ''} {step_name or ''}".lower()
    for bucket, patterns in EXCLUDED_PATTERNS:
        if any(pattern in text for pattern in patterns):
            return bucket
    if any(pattern in text for pattern in IN_SCOPE_PATTERNS):
        return IN_SCOPE
    return UNKNOWN


def is_in_scope(job_name: str, step_name: str) -> bool:
    return classify_job(job_name, step_name) == IN_SCOPE


def is_excluded(job_name: str, step_name: str) -> bool:
    """True only for a positively identified out-of-scope job.

    An unclassified job is not excluded here: the name simply did not match any
    pattern, which is a reason to inspect it rather than to discard it.
    """
    return classify_job(job_name, step_name) in EXCLUDED_BUCKETS
